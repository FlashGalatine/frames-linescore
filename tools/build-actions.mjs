// Builds the two pasteable action files from actions/src. Both actions need the same
// rules and Streamer.bot actions can't share code, so rules.cs is inlined into each.
//
//   node tools/build-actions.mjs           write actions/linescore-*.cs
//   node tools/build-actions.mjs --check   exit 1 if they're stale

import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const check = process.argv.includes('--check');

const HEADERS = {
  'linescore-command.cs': `// Streamer.bot "Linescore Command" action: the whole control surface in one parametric
// action. It changes the line score's global variables, then runs "Linescore Push".
//
// HOW TO USE (see README.md for the full walkthrough):
//   1. Streamer.bot -> Actions -> add an action named EXACTLY "Linescore Command".
//   2. Add a sub-action: Core -> C# -> Execute C# Code. Paste EVERYTHING below and click
//      COMPILE. It needs no added references.
//   3. Commands tab: create !ls, then add it as a TRIGGER on this action.
//
// It accepts three calling styles, so one action covers chat, Stream Deck and hotkeys:
//   A) One dispatch command (recommended): "!ls t1win", "!ls t1 3 20".
//   B) One chat command per action: !t1win, !t1, !undo... each added as a trigger.
//   C) Stream Deck / hotkey: Set Argument \`command\` (and \`value\`), then Run Action.
//
// Commands are listed in README.md. \`source\` marks a call from the control panel, for
// the repeat guard. \`_now\` (tests only) replaces the clock.
//
// GENERATED by tools/build-actions.mjs from actions/src. Edit there, not here.
`,
  'linescore-push.cs': `// Streamer.bot "Linescore Push" action: broadcasts the current line score to every
// connected overlay and control panel.
//
// HOW TO USE (see README.md for the full walkthrough):
//   1. Streamer.bot -> Actions -> add an action named EXACTLY "Linescore Push" (the name
//      matters: panel-core.js runs it by name on connect).
//   2. Add a sub-action: Core -> C# -> Execute C# Code. Paste EVERYTHING below and click
//      COMPILE. It needs no added references. No trigger is needed.
//
// All scoring rules are worked out here, so themes never compute anything. Any failure
// is logged and broadcast as { type: "linescore:error", message }.
//
// GENERATED by tools/build-actions.mjs from actions/src. Edit there, not here.
`,
};

const rules = readFileSync(join(ROOT, 'actions/src/rules.cs'), 'utf8').replace(/\s+$/, '');
const SOURCES = { 'linescore-command.cs': 'command.cs', 'linescore-push.cs': 'push.cs' };

let stale = 0;
for (const [out, src] of Object.entries(SOURCES)) {
  const body = readFileSync(join(ROOT, 'actions/src', src), 'utf8');
  if (!body.includes('    // @rules')) throw new Error(`${src} has no // @rules marker`);
  const text = (HEADERS[out] + '\n' + body.replace('    // @rules', rules)).replace(/\r\n/g, '\n');
  const path = join(ROOT, 'actions', out);
  if (check) {
    const have = existsSync(path) ? readFileSync(path, 'utf8').replace(/\r\n/g, '\n') : null;
    if (have !== text) { console.error(`${out} is stale: run node tools/build-actions.mjs`); stale++; }
  } else {
    writeFileSync(path, text, 'utf8');
    console.log(`wrote actions/${out}`);
  }
}
process.exit(stale ? 1 : 0);
