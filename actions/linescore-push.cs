using System;
using System.Text;
using System.Globalization;

public class CPHInline
{
    static readonly string[] LabelKeys = { "ball", "strike", "out" };
    static readonly string[] LabelNames = { "Ball", "Strike", "Out" };

    public bool Execute()
    {
        try
        {
            Derived d = Derive();
            var sb = new StringBuilder();
            sb.Append("{\"type\":\"linescore:update\"");
            sb.Append(",\"title\":").Append(JsonStr(Var("ls.title", "")));
            sb.Append(",\"totalLabel\":").Append(JsonStr(Var("ls.totallabel", "R")));
            sb.Append(",\"mode\":").Append(d.Fixed ? "\"fixed\"" : "\"free\"");
            sb.Append(",\"hidden\":").Append(Var("ls.hidden", "0") == "1" ? "true" : "false");

            sb.Append(",\"columns\":[");
            for (int i = 0; i < d.Shown; i++)
            {
                if (i > 0) sb.Append(',');
                sb.Append("{\"label\":").Append(JsonStr(ColumnLabel(d, i)));
                sb.Append(",\"worth\":").Append(d.Fixed ? Num(ColumnWorth(d, i)) : "null");
                sb.Append(",\"state\":").Append(i == d.Live ? "\"live\"" : d.Recorded(i) ? "\"done\"" : "\"open\"");
                sb.Append(",\"extra\":").Append(i >= d.Innings ? "true" : "false").Append('}');
            }
            sb.Append(']');

            sb.Append(",\"teams\":[");
            AppendTeam(sb, d, 0, Var("ls.t1name", "Visitor"));
            sb.Append(',');
            AppendTeam(sb, d, 1, Var("ls.t2name", "Home"));
            sb.Append(']');

            sb.Append(",\"lead\":").Append(d.Lead < 0 ? "null" : Num(d.Lead));
            sb.Append(",\"over\":").Append(d.Over ? "true" : "false");

            sb.Append(",\"labels\":[");
            for (int i = 0; i < LabelKeys.Length; i++)
            {
                string key = LabelKeys[i];
                int v;
                if (i > 0) sb.Append(',');
                sb.Append("{\"key\":").Append(JsonStr(key));
                sb.Append(",\"name\":").Append(JsonStr(Var("ls." + key + ".name", LabelNames[i])));
                sb.Append(",\"value\":").Append(Num(TryInt(Var("ls." + key + ".value", "0"), out v) ? Clamp(v, 0, CellMax) : 0));
                sb.Append(",\"on\":").Append(Var("ls." + key + ".on", "1") != "0" ? "true" : "false").Append('}');
            }
            sb.Append(']');

            // For the control panel. Themes don't need this.
            sb.Append(",\"settings\":{\"innings\":").Append(Num(d.Innings));
            sb.Append(",\"worth\":[");
            for (int i = 0; i < d.Worth.Length; i++)
            {
                if (i > 0) sb.Append(',');
                sb.Append(Num(d.Worth[i]));
            }
            sb.Append("],\"extraWorth\":").Append(Num(d.ExtraWorth));
            sb.Append(",\"extraOn\":").Append(d.ExtraOn ? "true" : "false");
            sb.Append(",\"colLabel\":").Append(JsonStr(Var("ls.collabel", "")));
            sb.Append(",\"extraLabel\":").Append(JsonStr(Var("ls.extralabel", "")));
            sb.Append("}}");

            CPH.WebsocketBroadcastJson(sb.ToString());
            return true;
        }
        catch (Exception ex)
        {
            CPH.LogWarn("[Linescore Push] ERROR: " + ex);
            CPH.WebsocketBroadcastJson("{\"type\":\"linescore:error\",\"message\":" + JsonStr(ex.Message) + "}");
            return false;
        }
    }

    void AppendTeam(StringBuilder sb, Derived d, int team, string name)
    {
        sb.Append("{\"name\":").Append(JsonStr(name)).Append(",\"scores\":[");
        for (int i = 0; i < d.Shown; i++)
        {
            if (i > 0) sb.Append(',');
            int? v = d.Cell(team, i);
            sb.Append(v.HasValue ? Num(v.Value) : "null");
        }
        sb.Append("],\"total\":").Append(Num(d.Totals[team])).Append('}');
    }

    string ColumnLabel(Derived d, int i)
    {
        if (i < d.Innings)
        {
            string prefix = Var("ls.collabel", "");
            return prefix.Length > 0 ? prefix + " " + Num(i + 1) : Num(i + 1);
        }
        string extra = Var("ls.extralabel", "");
        if (extra.Length == 0) return Num(i + 1);
        int ordinal = i - d.Innings + 1;
        return ordinal == 1 ? extra : extra + " " + Num(ordinal);
    }

    static string Num(int n) { return n.ToString(CultureInfo.InvariantCulture); }

    // Minimal, correct JSON string encoder (escapes quotes, backslashes, controls).
    static string JsonStr(string s)
    {
        if (s == null) return "\"\"";
        var sb = new StringBuilder(s.Length + 2);
        sb.Append('"');
        foreach (char c in s)
        {
            switch (c)
            {
                case '"':  sb.Append("\\\""); break;
                case '\\': sb.Append("\\\\"); break;
                case '\b': sb.Append("\\b"); break;
                case '\f': sb.Append("\\f"); break;
                case '\n': sb.Append("\\n"); break;
                case '\r': sb.Append("\\r"); break;
                case '\t': sb.Append("\\t"); break;
                default:
                    if (c < ' ') sb.Append("\\u").Append(((int)c).ToString("x4", CultureInfo.InvariantCulture));
                    else sb.Append(c);
                    break;
            }
        }
        sb.Append('"');
        return sb.ToString();
    }

    // ── Shared rules (actions/src/rules.cs): both actions carry an identical copy, ──
    // ── because Streamer.bot actions can't share code. Edit there, not here.       ──
    const int MaxColumns = 12;
    const int CellMax = 99;

    class Derived
    {
        public int Innings;
        public bool Fixed;
        public int[] Worth;
        public int ExtraWorth;
        public bool ExtraOn;
        public int?[][] Cells = new int?[2][];
        public int[] Totals = new int[2];
        public int Shown;
        public bool Over;
        public int Lead = -1;   // -1 = nobody leads
        public int Live = -1;   // -1 = no live column
        public bool TiedAtCap;

        public int? Cell(int team, int i) { int?[] c = Cells[team]; return i < c.Length ? c[i] : (int?)null; }
        public bool Recorded(int i) { return Cell(0, i).HasValue && Cell(1, i).HasValue; }
        public bool AllRecorded(int n) { for (int i = 0; i < n; i++) if (!Recorded(i)) return false; return true; }
    }

    // Everything a theme or a command needs to know, worked out from the stored state.
    Derived Derive()
    {
        var d = new Derived();
        int n;
        d.Innings = Clamp(TryInt(Var("ls.innings", "9"), out n) ? n : 9, 1, MaxColumns);
        d.Fixed = Var("ls.mode", "free") == "fixed";
        d.Worth = ParseWorth(Var("ls.worth", ""));
        d.ExtraWorth = TryInt(Var("ls.extraworth", "5"), out n) ? Clamp(n, 0, CellMax) : 5;
        d.ExtraOn = Var("ls.extra", "on") != "off";
        d.Cells[0] = ParseScores(Var("ls.t1scores", ""));
        d.Cells[1] = ParseScores(Var("ls.t2scores", ""));
        for (int t = 0; t < 2; t++)
            foreach (int? v in d.Cells[t]) d.Totals[t] += v.GetValueOrDefault();

        int highest = -1;
        for (int i = 0; i < MaxColumns; i++)
            if (d.Cell(0, i).HasValue || d.Cell(1, i).HasValue) highest = i;
        d.Shown = Math.Max(d.Innings, highest + 1);
        while (d.AllRecorded(d.Shown) && d.Totals[0] == d.Totals[1] && d.ExtraOn && d.Shown < MaxColumns) d.Shown++;

        d.Over = d.AllRecorded(d.Shown);
        d.Lead = d.Totals[0] > d.Totals[1] ? 0 : d.Totals[1] > d.Totals[0] ? 1 : -1;
        if (!d.Over)
        {
            if (d.Fixed)
            {
                for (int i = 0; i < d.Shown; i++)
                    if (!d.Recorded(i)) { d.Live = i; break; }
            }
            else
            {
                d.Live = Clamp(TryInt(Var("ls.live", "0"), out n) ? n : 0, 0, d.Shown - 1);
            }
        }
        d.TiedAtCap = d.Over && d.Totals[0] == d.Totals[1] && d.ExtraOn && d.Shown == MaxColumns;
        return d;
    }

    // What a column is worth in fixed mode: its listed points, else the extra's.
    static int ColumnWorth(Derived d, int i)
    {
        return i < d.Innings && i < d.Worth.Length ? d.Worth[i] : d.ExtraWorth;
    }

    static int?[] ParseScores(string csv)
    {
        string[] parts = (csv ?? "").Split(',');
        var cells = new int?[Math.Min(parts.Length, MaxColumns)];
        for (int i = 0; i < cells.Length; i++)
        {
            int n;
            if (TryInt(parts[i], out n)) cells[i] = Clamp(n, 0, CellMax);
        }
        return cells;
    }

    static int[] ParseWorth(string csv)
    {
        string t = (csv ?? "").Trim();
        if (t.Length == 0) return new int[0];
        string[] parts = t.Split(',');
        var list = new int[parts.Length];
        for (int i = 0; i < parts.Length; i++)
        {
            int n;
            list[i] = TryInt(parts[i], out n) ? Clamp(n, 0, CellMax) : 0;
        }
        return list;
    }

    // GetGlobalVar returns null when unset: fall back to the default, but keep an
    // explicitly-set empty string.
    string Var(string key, string dflt)
    {
        var v = CPH.GetGlobalVar<string>(key, true);
        return v == null ? dflt : v;
    }

    static bool TryInt(string s, out int n)
    {
        return int.TryParse((s ?? "").Trim(), NumberStyles.AllowLeadingSign, CultureInfo.InvariantCulture, out n);
    }

    static int Clamp(int v, int lo, int hi) { return Math.Min(hi, Math.Max(lo, v)); }
    // ── End of shared rules ──
}
