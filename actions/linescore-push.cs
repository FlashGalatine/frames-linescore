// Streamer.bot "Linescore Push" action: broadcasts the current line score to every
// connected overlay and control panel.
//
// HOW TO USE (see README.md for the full walkthrough):
//   1. Streamer.bot -> Actions -> add an action named EXACTLY "Linescore Push" (the name
//      matters: panel-core.js runs it by name on connect).
//   2. Add a sub-action: Core -> C# -> Execute C# Code. Paste EVERYTHING below and click
//      COMPILE. It needs no added references. No trigger is needed.
//
// All scoring rules are worked out here, so themes never compute anything. Any failure
// is logged and broadcast as { type: "linescore:error", message }.
//
